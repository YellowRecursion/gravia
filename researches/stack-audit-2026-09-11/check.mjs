import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { theme } = require('antd');
const ru = require('antd/locale/ru_RU').default;
const en = require('antd/locale/en_US').default;
const { themeDark, themeLight } = require('dockview-react');
const { createInstance } = require('i18next');
const light = theme.getDesignToken({ algorithm: theme.defaultAlgorithm });
const dark = theme.getDesignToken({ algorithm: theme.darkAlgorithm });
const compact = theme.getDesignToken({ algorithm: [theme.darkAlgorithm, theme.compactAlgorithm] });
assert.notEqual(light.colorBgContainer, dark.colorBgContainer);
assert.ok(compact.controlHeight < dark.controlHeight);
assert.equal(ru.locale, 'ru'); assert.equal(en.locale, 'en');
assert.notEqual(ru.Modal.cancelText, en.Modal.cancelText);
assert.notEqual(themeLight.className, themeDark.className);
const instance = createInstance();
await instance.init({ lng: 'ru', resources: { ru: { translation: { run: 'Рассчитать' } }, en: { translation: { run: 'Calculate' } } } });
assert.equal(instance.t('run'), 'Рассчитать');
await instance.changeLanguage('en'); assert.equal(instance.t('run'), 'Calculate');
console.log(JSON.stringify({ status: 'passed', ant: { light: light.colorBgContainer, dark: dark.colorBgContainer, defaultHeight: dark.controlHeight, compactHeight: compact.controlHeight, ruCancel: ru.Modal.cancelText, enCancel: en.Modal.cancelText }, dockview: { light: themeLight.className, dark: themeDark.className }, i18n: 'ru/en switch passed', scope: 'API values only; no browser rendering or Electron launch' }, null, 2));
